-- omarchy.clipboard: port of the Omarchy 4.5 shell plugin "omarchy.clipboard" (kind: overlay).
--
-- A clipboard manager to view and paste history. Records every copy (text, files, images)
-- with hs.pasteboard.watcher into an IN-MEMORY history (newest first, 500 entries, duplicates
-- move to the top) and shows the Omarchy two-pane picker in a borderless hs.webview:
-- search line on top, result list on the left, full preview on the right.
--
--   type            filter            Return          paste into the previous app (Cmd+V)
--   Up/Down         move (wraps)      Shift+Return    copy only
--   PgUp/PgDn       move 6            Option+Return   open (files, links, images)
--   Home/End        first/last        Delete (fn+⌫)   remove entry
--   Esc             clear / close     Shift+Delete    clear history (confirm)
--
-- Privacy (clinical machine): nothing copied is ever logged, written to disk or published
-- with `omniwmctl shell set`; history and image previews live only in this Lua state and are
-- gone when Hammerspoon reloads. Copies are ignored while Citrix Viewer (the EMR) or a
-- password manager is frontmost (or was within the last few seconds), and whenever the
-- pasteboard carries a concealed/transient marker (org.nspasteboard.ConcealedType etc.,
-- the macOS equivalent of x-kde-passwordManagerHint).
