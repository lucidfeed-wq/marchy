---------------------------------------------------------------- helpers
local function now() return hs.timer.secondsSinceEpoch() end

local function trim(s) return (tostring(s or ""):gsub("^%s+", ""):gsub("%s+$", "")) end

local function encodePath(p)
  return (p:gsub("[^%w/%._~%-]", function(c) return string.format("%%%02X", string.byte(c)) end))
end

local function decodeFileUri(uri)
  local value = trim(uri)
  if value:sub(1, 7) ~= "file://" then return "" end
  local path = value:sub(8)
  if path:sub(1, 10) == "localhost/" then path = path:sub(10) end
  if path:sub(1, 1) ~= "/" then return "" end
  return (path:gsub("%%(%x%x)", function(h) return string.char(tonumber(h, 16)) end))
end

local function fileName(path)
  return path:match("([^/]*)$") or path
end

local IMAGE_EXT = { png = true, jpg = true, jpeg = true, webp = true, gif = true, bmp = true,
  tif = true, tiff = true, heic = true }
local function isImagePath(path)
  local ext = path:match("%.([%w]+)$")
  return ext ~= nil and IMAGE_EXT[ext:lower()] == true
end

-- Cut to at most n bytes without splitting a UTF-8 sequence.
local function utf8Prefix(s, n)
  if #s <= n then return s end
  local cut = n
  while cut > 0 do
    local b = s:byte(cut + 1)
    if not b or b < 0x80 or b >= 0xC0 then break end
    cut = cut - 1
  end
  return s:sub(1, cut)
end

-- Upstream cappedEntry: search/render only a prefix, cut on a line break when possible.
local function capText(text)
  if #text <= DISPLAY_TEXT_LIMIT then return text end
  local head = utf8Prefix(text, DISPLAY_TEXT_LIMIT)
  local nl = head:match(".*()\n")
  if nl and nl > 1 then return head:sub(1, nl - 1) end
  return head
end

local function filePathsOf(text)
  local paths = {}
  for line in (text .. "\n"):gmatch("([^\n]*)\n") do
    local p = decodeFileUri((line:gsub("\r$", "")))
    if p ~= "" then paths[#paths + 1] = p end
  end
  return paths
end

local function validUtf8(s)
  if type(s) ~= "string" then return false end
  if utf8 and utf8.len then return utf8.len(s) ~= nil end
  return true
end

---------------------------------------------------------------- history (ClipboardHistory.js)
local function textEntry(text)
  uidSeq = uidSeq + 1
  local capped = capText(text)
  local paths = filePathsOf(capped)
  local fileText = ""
  if #paths == 1 then fileText = fileName(paths[1])
  elseif #paths > 1 then fileText = string.format("%d files", #paths) end
  return {
    uid = uidSeq, type = "text", text = text, capped = capped, paths = paths,
    fileText = fileText,
    search = (capped .. " " .. fileText):lower(),
  }
end

local function imageEntry(img, mime, thumb, hash)
  uidSeq = uidSeq + 1
  local capturedAt = os.date("%A %H:%M")
  return {
    uid = uidSeq, type = "image", image = img, mime = mime, thumb = thumb, hash = hash,
    capturedAt = capturedAt, imgId = "e" .. uidSeq,
    search = ("image screenshot " .. mime .. " " .. capturedAt):lower(),
  }
end

local function sameEntry(a, b)
  if a.type ~= b.type then return false end
  if a.type == "image" then return a.hash == b.hash end
  return a.text == b.text
end

local function addEntry(entry)
  local nextList = { entry }
  local images = entry.type == "image" and 1 or 0
  for _, e in ipairs(history) do
    if #nextList >= HISTORY_LIMIT then break end
    if not sameEntry(e, entry) then
      if e.type == "image" then
        if images < IMAGE_LIMIT then
          images = images + 1
          nextList[#nextList + 1] = e
        end
      else
        nextList[#nextList + 1] = e
      end
    end
  end
  history = nextList
end

local function findEntry(uid)
  if type(uid) ~= "number" then return nil end
  for i, e in ipairs(history) do
    if e.uid == uid then return e, i end
  end
  return nil
end

---------------------------------------------------------------- previews (in memory only)
local function thumbOf(img)
  local size = img:size()
  local w, h = size and size.w or 0, size and size.h or 0
  local small = img
  local longest = math.max(w, h, 1)
  if longest > THUMB_MAX then
    local scale = THUMB_MAX / longest
    small = img:setSize({ w = math.floor(w * scale + 0.5), h = math.floor(h * scale + 0.5) }, true) or img
  end
  return small:encodeAsURLString(false, "PNG")
end

local function fileThumb(path)
  thumbTick = thumbTick + 1
  local c = fileThumbs[path]
  if c then
    c.used = thumbTick
    return c
  end
  c = { used = thumbTick }
  local attr = hs.fs.attributes(path)
  if attr and attr.mode == "file" and (attr.size or 0) <= MAX_PREVIEW_FILE then
    local okI, img = pcall(hs.image.imageFromPath, path)
    if okI and img then
      local okT, data = pcall(thumbOf, img)
      if okT and type(data) == "string" then
        thumbSeq = thumbSeq + 1
        c.id, c.data = "f" .. thumbSeq, data
      end
    end
  end
  fileThumbs[path] = c
  fileThumbCount = fileThumbCount + 1
  while fileThumbCount > FILE_THUMB_LIMIT do
    local oldKey, oldUsed = nil, math.huge
    for k, v in pairs(fileThumbs) do
      if v.used < oldUsed then oldKey, oldUsed = k, v.used end
    end
    if not oldKey then break end
    if fileThumbs[oldKey].id then sentImages[fileThumbs[oldKey].id] = nil end
    fileThumbs[oldKey] = nil
    fileThumbCount = fileThumbCount - 1
  end
  return c
end

---------------------------------------------------------------- display rows
local function previewOf(e)
  if e.type == "image" then
    if e.capturedAt == "" then return "Image" end
    if e.mime == "image/png" then return "Screenshot from " .. e.capturedAt end
    return "Image from " .. e.capturedAt
  end
  if e.fileText ~= "" then return e.fileText end
  return (e.capped:gsub("%s+", " "))
end

local function displayRows(query)
  local needle = trim(query):lower()
  local rows, imgs = {}, {}
  for _, e in ipairs(history) do
    if needle == "" or e.search:find(needle, 1, true) then
      local row = { uid = e.uid, p = previewOf(e) }
      if e.type == "image" then
        row.t, row.f, row.img = "image", "", e.imgId
        if not sentImages[e.imgId] then imgs[e.imgId] = e.thumb end
      else
        local isFile = #e.paths > 0
        row.t = isFile and "file" or "text"
        row.f = isFile and table.concat(e.paths, "\n") or e.capped
        if isFile and #e.paths == 1 and isImagePath(e.paths[1]) then
          local c = fileThumb(e.paths[1])
          if c.id then
            row.img = c.id
            if not sentImages[c.id] then imgs[c.id] = c.data end
          end
        end
      end
      if validUtf8(row.p) and validUtf8(row.f) then rows[#rows + 1] = row end
      if #rows >= DISPLAY_LIMIT then break end
    end
  end
  return rows, imgs
end

local function js(code)
  if not view then return end
  local ok, err = pcall(function() view:evaluateJavaScript(code) end)
  if not ok then log.w("clipboard: page update failed: %s", tostring(err):sub(1, 120)) end
end

local function pushRows()
  if not view then return end
  local rows, imgs = displayRows(filter)
  local payload = { q = filter, total = #history, rows = rows, imgs = imgs }
  if next(imgs) == nil then payload.imgs = nil end
  if #rows == 0 then payload.rows = nil end
  local ok, text = pcall(hs.json.encode, payload)
  if not ok or type(text) ~= "string" then
    log.w("clipboard: could not encode %d rows", #rows)
    return
  end
  for id in pairs(imgs) do sentImages[id] = true end
  js("R(" .. text .. ")")
end

---------------------------------------------------------------- capture
local function frontBundle()
  local ok, b = pcall(function()
    local app = hs.application.frontmostApplication()
    return app and app:bundleID()
  end)
  return ok and b or nil
end

local function excludedNow()
  local b = frontBundle()
  if b and EXCLUDED_APPS[b] then
    lastExcludedAt = now()
    return true
  end
  return now() - lastExcludedAt < EXCLUDE_GRACE
end

local function pasteboardTypes()
  local set = {}
  local okA, a = pcall(hs.pasteboard.pasteboardTypes)
  if okA and type(a) == "table" then for _, t in ipairs(a) do set[t] = true end end
  local okB, b = pcall(hs.pasteboard.contentTypes)
  if okB and type(b) == "table" then for _, t in ipairs(b) do set[t] = true end end
  return set
end

local function concealed(types)
  for _, t in ipairs(CONCEALED_TYPES) do
    if types[t] then return true end
  end
  for t in pairs(types) do
    if type(t) == "string" and t:lower():find("citrix", 1, true) then return true end
  end
  return false
end

-- Finder copies: absolute paths -> "file://" URI lines (the representation upstream stores).
local function copiedFiles(types)
  if not (types["public.file-url"] or types["NSFilenamesPboardType"]) then return nil end
  local paths = {}
  local okP, list = pcall(hs.pasteboard.readPListForUTI, nil, "NSFilenamesPboardType")
  if okP and type(list) == "table" then
    for _, p in ipairs(list) do
      if type(p) == "string" and p:sub(1, 1) == "/" then paths[#paths + 1] = p end
    end
  end
  if #paths == 0 then
    local okU, urls = pcall(hs.pasteboard.readURL, nil, true)
    if okU and type(urls) == "table" then
      if urls.url or urls.filePath then urls = { urls } end
      for _, u in ipairs(urls) do
        local p = nil
        if type(u) == "table" then p = u.filePath or decodeFileUri(u.url or "")
        elseif type(u) == "string" then p = decodeFileUri(u) end
        if type(p) == "string" and p:sub(1, 1) == "/" and not p:find("^/%.file/id=") then
          paths[#paths + 1] = p
        end
      end
    end
  end
  if #paths == 0 then return nil end
  local lines = {}
  for i, p in ipairs(paths) do lines[i] = "file://" .. encodePath(p) end
  return table.concat(lines, "\n")
end

local function imageMime(types)
  for _, t in ipairs(IMAGE_TYPES) do
    if types[t[1]] then return t[2] end
  end
  return nil
end

-- Browsers' "Copy Image" also put the image URL on the pasteboard as text.
local function isBareUrl(text)
  local t = trim(text)
  return not t:find("%s") and t:match("^%a[%w+.-]*://") ~= nil
end

local function capture()
  if excludedNow() then return end
  local types = pasteboardTypes()
  if concealed(types) then return end

  local entry = nil
  local files = copiedFiles(types)
  if files then
    entry = textEntry(files)
  else
    local text = nil
    local okS, s = pcall(hs.pasteboard.readString)
    if okS and type(s) == "string" and s:find("%S") then text = s end
    local mime = imageMime(types)
    if mime and (not text or isBareUrl(text)) then
      local okI, img = pcall(hs.pasteboard.readImage)
      if okI and img then
        local okT, thumb = pcall(thumbOf, img)
        if okT and type(thumb) == "string" then
          local hash = thumb
          if hs.hash and hs.hash.SHA256 then
            local okH, h = pcall(hs.hash.SHA256, thumb)
            if okH and h then hash = h end
          end
          entry = imageEntry(img, mime, thumb, hash)
        end
      end
    end
    if not entry and text then
      if #text > MAX_TEXT then
        log.w("clipboard: skipped a %d-byte copy (over limit)", #text)
        return
      end
      entry = textEntry(text)
    end
  end
  if not entry then return end
  addEntry(entry)
  if view then pushRows() end
end

local function safeCapture()
  local ok, err = pcall(capture)
  if not ok then log.e("clipboard: capture failed: %s", tostring(err):sub(1, 160)) end
end

---------------------------------------------------------------- paste / copy / open
local function writeEntry(e)
  if e.type == "image" then
    return hs.pasteboard.writeObjects(e.image)
  end
  if #e.paths > 0 then
    local objs = {}
    for _, p in ipairs(e.paths) do
      objs[#objs + 1] = { url = "file://" .. encodePath(p), __luaSkinType = "NSURL" }
    end
    local ok, res = pcall(hs.pasteboard.writeObjects, objs)
    if ok and res then return true end
  end
  return hs.pasteboard.setContents(e.text)
end

local function refocus(done)
  local win, app = prevWin, prevApp
  pcall(function()
    if win and win:application() then win:focus()
    elseif app and app:isRunning() then app:activate() end
  end)
  if done then hs.timer.doAfter(0.15, done) end
end

local function deliver(e, how)
  M.close()
  local ok, res = pcall(writeEntry, e)
  if not ok or not res then
    toast.warn("Could not copy to the clipboard")
    return
  end
  if how == "copy" then
    refocus()
    return
  end
  hs.timer.doAfter(0.05, function()
    refocus(function() hs.eventtap.keyStroke({ "cmd" }, "v", 20000) end)
  end)
end

local function whenFrontmost(bundle, tries, fn)
  if frontBundle() == bundle then return fn() end
  if tries <= 0 then return toast.warn("Could not open the image") end
  hs.timer.doAfter(0.2, function() whenFrontmost(bundle, tries - 1, fn) end)
end

local function openEntry(e)
  M.close()
  if e.type == "image" then
    -- No temp files: hand the image to Preview via File > New from Clipboard (Cmd+N).
    local ok = pcall(writeEntry, e)
    if not ok then return toast.warn("Could not open the image") end
    hs.application.launchOrFocusByBundleID("com.apple.Preview")
    whenFrontmost("com.apple.Preview", 15, function() hs.eventtap.keyStroke({ "cmd" }, "n", 20000) end)
    return
  end
  if #e.paths > 0 then
    local args = {}
    for _, p in ipairs(e.paths) do
      if hs.fs.attributes(p) then args[#args + 1] = p end
    end
    if #args == 0 then return toast.warn("File no longer exists") end
    hs.task.new(OPEN, function(code)
      if code ~= 0 then toast.warn("Could not open file") end
    end, args):start()
    return
  end
  local t = trim(e.text)
  if not t:find("%s") and (t:match("^https?://%S+$") or t:match("^mailto:%S+$")) then
    hs.urlevent.openURL(t)
    return
  end
  toast.show("Nothing to open", 1.2)
end

