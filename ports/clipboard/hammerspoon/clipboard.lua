local function onMessage(msg)
  local body = type(msg) == "table" and msg.body or nil
  if type(body) ~= "table" or type(body.op) ~= "string" then return end
  local op = body.op
  if op == "filter" then
    filter = type(body.q) == "string" and body.q:sub(1, 1000) or ""
    pushRows()
  elseif op == "close" then
    M.close()
    refocus()
  elseif op == "clear" then
    history = {}
    fileThumbs, fileThumbCount = {}, 0
    pushRows()
  elseif op == "remove" or op == "paste" or op == "copy" or op == "open" then
    local e, i = findEntry(tonumber(body.uid))
    if not e then
      pushRows()
      return
    end
    if op == "remove" then
      table.remove(history, i)
      pushRows()
    elseif op == "open" then
      openEntry(e)
    else
      deliver(e, op)
    end
  end
end

---------------------------------------------------------------- open / close
function M.close()
  if view then
    local v = view
    view = nil
    pcall(function() v:delete() end)
  end
end

function M.isOpen() return view ~= nil end

function M.open(askClear)
  if view then
    if askClear then js("askClear()") end
    return
  end
  prevApp = hs.application.frontmostApplication()
  prevWin = hs.window.frontmostWindow()
  filter = ""
  sentImages = {}
  if not ucc then
    ucc = hs.webview.usercontent.new(UCC)
    ucc:setCallback(function(msg)
      local ok, err = pcall(onMessage, msg)
      if not ok then log.e("clipboard: action failed: %s", tostring(err):sub(1, 160)) end
    end)
  end
  local screen = hs.mouse.getCurrentScreen() or hs.screen.mainScreen()
  local frame = screen:frame()
  local ok, err = pcall(function()
    view = hs.webview.new(frame, { developerExtrasEnabled = false }, ucc)
      :windowStyle({ "borderless" })
      :transparent(true)
      :allowTextEntry(true)
      :level(hs.drawing.windowLevels.modalPanel)
      :shadow(false)
      :closeOnEscape(false)
      :deleteOnClose(true)
      :html(page(askClear))
    view:show()
    view:bringToFront(true)
    local win = view:hswindow()
    if win then win:focus() end
  end)
  if not ok then
    log.e("clipboard: could not open overlay: %s", tostring(err))
    M.close()
  end
end

function M.toggle()
  if view then
    M.close()
    refocus()
  else
    M.open(false)
  end
end

