function M.start()
  M.stop()
  appWatcher = hs.application.watcher.new(function(_, event, app)
    if event == hs.application.watcher.activated or event == hs.application.watcher.deactivated then
      local okB, b = pcall(function() return app and app:bundleID() end)
      if okB and b and EXCLUDED_APPS[b] then lastExcludedAt = now() end
    end
  end)
  appWatcher:start()
  if hs.pasteboard.watcher then
    watcher = hs.pasteboard.watcher.new(function() safeCapture() end)
    pcall(function() watcher:start() end)
  else
    -- Older Hammerspoon: poll the change counter (cheap, no content read unless it changed).
    local seen = hs.pasteboard.changeCount()
    watcher = hs.timer.doEvery(2, function()
      local c = hs.pasteboard.changeCount()
      if c ~= seen then
        seen = c
        safeCapture()
      end
    end)
  end
  -- Like upstream's currentProc: snapshot what is on the clipboard right now.
  startTimer = hs.timer.doAfter(1, safeCapture)
  log.i("clipboard: started (history in memory only)")
  return M
end

function M.stop()
  if startTimer then startTimer:stop() startTimer = nil end
  if watcher then pcall(function() watcher:stop() end) watcher = nil end
  if appWatcher then appWatcher:stop() appWatcher = nil end
  M.close()
end

return M
